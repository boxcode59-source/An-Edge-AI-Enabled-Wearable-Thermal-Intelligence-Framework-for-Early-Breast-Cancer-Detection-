import torch
import torch.nn as nn
import torch.nn.functional as F

# ----------------------------------------------------------
# Conv Block
# ----------------------------------------------------------

class ConvBlock(nn.Module):

    def __init__(self,in_channels,out_channels):

        super().__init__()

        self.block=nn.Sequential(

            nn.Conv2d(
                in_channels,
                out_channels,
                kernel_size=3,
                padding=1,
                bias=False
            ),

            nn.BatchNorm2d(out_channels),

            nn.GELU()

        )

    def forward(self,x):

        return self.block(x)

# ----------------------------------------------------------
# Multi Scale Feature Pyramid
# ----------------------------------------------------------

class MultiScaleThermalFeaturePyramid(nn.Module):

    def __init__(self,in_channels=768):

        super().__init__()

        # 1x1 Projection
        self.proj=nn.Conv2d(
            in_channels,
            256,
            kernel_size=1
        )

        # Multi-scale branches
        self.scale1=ConvBlock(256,256)

        self.scale2=nn.Sequential(

            nn.MaxPool2d(2),

            ConvBlock(256,256)

        )

        self.scale3=nn.Sequential(

            nn.MaxPool2d(4),

            ConvBlock(256,256)

        )

        self.scale4=nn.Sequential(

            nn.AdaptiveAvgPool2d(1),

            ConvBlock(256,256)

        )

        self.fusion=nn.Sequential(

            nn.Conv2d(
                1024,
                512,
                kernel_size=3,
                padding=1
            ),

            nn.BatchNorm2d(512),

            nn.GELU()

        )

    def forward(self,x):

        x=self.proj(x)

        s1=self.scale1(x)

        s2=self.scale2(x)

        s3=self.scale3(x)

        s4=self.scale4(x)

        s2=F.interpolate(
            s2,
            size=s1.shape[2:],
            mode='bilinear',
            align_corners=False
        )

        s3=F.interpolate(
            s3,
            size=s1.shape[2:],
            mode='bilinear',
            align_corners=False
        )

        s4=F.interpolate(
            s4,
            size=s1.shape[2:],
            mode='bilinear',
            align_corners=False
        )

        out=torch.cat(
            [s1,s2,s3,s4],
            dim=1
        )

        out=self.fusion(out)

        return out

