import torch
import torch.nn as nn
import torch.nn.functional as F

# ----------------------------------------------------------
# Adaptive Feature Aggregation Layer
# ----------------------------------------------------------

class AFAL(nn.Module):

    def __init__(self,
                 conv_channels=768,
                 swin_channels=768,
                 thermal_channels=512):

        super(AFAL,self).__init__()

        self.conv_proj = nn.Conv2d(conv_channels,256,1)

        self.swin_proj = nn.Conv2d(swin_channels,256,1)

        self.thermal_proj = nn.Conv2d(thermal_channels,256,1)

        # Adaptive Weights
        self.weight_generator = nn.Sequential(

            nn.AdaptiveAvgPool2d(1),

            nn.Conv2d(768,256,1),

            nn.ReLU(inplace=True),

            nn.Conv2d(256,3,1),

            nn.Softmax(dim=1)

        )

        # Final Fusion
        self.fusion = nn.Sequential(

            nn.Conv2d(
                256,
                512,
                kernel_size=3,
                padding=1,
                bias=False
            ),

            nn.BatchNorm2d(512),

            nn.GELU(),

            nn.Conv2d(
                512,
                512,
                kernel_size=3,
                padding=1,
                bias=False
            ),

            nn.BatchNorm2d(512),

            nn.GELU()

        )

        self.pool = nn.AdaptiveAvgPool2d(1)

    def forward(self,
                conv_feat,
                swin_feat,
                thermal_feat):

        conv_feat = self.conv_proj(conv_feat)

        swin_feat = self.swin_proj(swin_feat)

        thermal_feat = self.thermal_proj(thermal_feat)

        fusion_input = torch.cat(
            [conv_feat,swin_feat,thermal_feat],
            dim=1
        )

        weights = self.weight_generator(fusion_input)

        w1 = weights[:,0:1,:,:]

        w2 = weights[:,1:2,:,:]

        w3 = weights[:,2:3,:,:]

        fused = (w1*conv_feat)+(w2*swin_feat)+(w3*thermal_feat)

        fused = self.fusion(fused)

        embedding = self.pool(fused)

        embedding = torch.flatten(embedding,1)

        return fused,embedding

