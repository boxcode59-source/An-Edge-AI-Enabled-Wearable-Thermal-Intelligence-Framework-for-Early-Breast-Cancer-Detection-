import numpy as np
import pandas as pd
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import brier_score_loss


# ============================================================
# Confidence Calibration Module
# ============================================================

class ConfidenceCalibrationModule:

    def __init__(self):
        self.scaler = MinMaxScaler()


    # --------------------------------------------------------
    # Confidence Score Generation
    # --------------------------------------------------------

    def generate_confidence_score(self, features):

        normalized_features = self.scaler.fit_transform(
            features.reshape(-1,1)
        )

        confidence_score = np.mean(normalized_features)

        confidence_score = np.clip(
            confidence_score,
            0,
            1
        )

        return confidence_score



    # --------------------------------------------------------
    # Uncertainty Score Calculation
    # --------------------------------------------------------

    def calculate_uncertainty(self, features):

        variance = np.var(features)

        uncertainty_score = variance / (
            variance + 1
        )

        return uncertainty_score



    # --------------------------------------------------------
    # Reliability Estimation
    # --------------------------------------------------------

    def reliability_estimation(
            self,
            confidence,
            uncertainty):

        reliability = confidence * (
            1 - uncertainty
        )

        reliability = np.clip(
            reliability,
            0,
            1
        )

        return reliability



    # --------------------------------------------------------
    # Confidence Calibration
    # --------------------------------------------------------

    def calibrate_confidence(
            self,
            features):

        confidence = self.generate_confidence_score(
            features
        )

        uncertainty = self.calculate_uncertainty(
            features
        )

        reliability = self.reliability_estimation(
            confidence,
            uncertainty
        )


        calibrated_features = np.concatenate(
            [
                features,
                [
                    confidence,
                    uncertainty,
                    reliability
                ]
            ]
        )


        return calibrated_features, {
            "Confidence Score":confidence,
            "Uncertainty Score":uncertainty,
            "Reliability Score":reliability
        }



