import torch
import torch.nn as nn
import torch.nn.functional as F

# ----------------------------------------------------------
# Channel Attention
# ----------------------------------------------------------

class ChannelAttention(nn.Module):

    def __init__(self, channels, reduction=16):

        super().__init__()

        self.avg_pool = nn.AdaptiveAvgPool2d(1)

        self.max_pool = nn.AdaptiveMaxPool2d(1)

        self.mlp = nn.Sequential(

            nn.Conv2d(channels, channels//reduction, 1, bias=False),
            nn.ReLU(inplace=True),
            nn.Conv2d(channels//reduction, channels, 1, bias=False)

        )

        self.sigmoid = nn.Sigmoid()

    def forward(self,x):

        avg = self.mlp(self.avg_pool(x))

        mx = self.mlp(self.max_pool(x))

        attention = self.sigmoid(avg + mx)

        return x * attention


# ----------------------------------------------------------
# Spatial Attention
# ----------------------------------------------------------

class SpatialAttention(nn.Module):

    def __init__(self):

        super().__init__()

        self.conv = nn.Conv2d(
            2,
            1,
            kernel_size=7,
            padding=3,
            bias=False
        )

        self.sigmoid = nn.Sigmoid()

    def forward(self,x):

        avg = torch.mean(x,dim=1,keepdim=True)

        mx,_ = torch.max(x,dim=1,keepdim=True)

        attention = torch.cat([avg,mx],dim=1)

        attention = self.sigmoid(self.conv(attention))

        return x * attention


# ----------------------------------------------------------
# Temporal Memory Attention Module
# ----------------------------------------------------------

class TMAM(nn.Module):

    def __init__(self,in_channels=512):

        super().__init__()

        self.channel_attention = ChannelAttention(in_channels)

        self.spatial_attention = SpatialAttention()

        self.memory = nn.GRU(

            input_size=in_channels,

            hidden_size=in_channels,

            batch_first=True

        )

        self.output = nn.Sequential(

            nn.Conv2d(
                in_channels,
                in_channels,
                kernel_size=3,
                padding=1
            ),

            nn.BatchNorm2d(in_channels),

            nn.GELU()

        )

    def forward(self,x):

        B,C,H,W = x.shape

        x = self.channel_attention(x)

        x = self.spatial_attention(x)

        sequence = x.view(B,C,H*W)

        sequence = sequence.permute(0,2,1)

        memory,_ = self.memory(sequence)

        memory = memory.permute(0,2,1)

        memory = memory.view(B,C,H,W)

        output = self.output(memory)

        return output


