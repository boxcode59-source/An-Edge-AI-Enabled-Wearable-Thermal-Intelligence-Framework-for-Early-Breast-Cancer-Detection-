import torch
import torch.nn as nn
import torch.nn.functional as F

# ----------------------------------------------------------
# Bilateral Thermal Difference Mapping
# ----------------------------------------------------------

class BilateralDifferenceMapping(nn.Module):

    def __init__(self, channels=512):

        super().__init__()

        self.refine = nn.Sequential(

            nn.Conv2d(
                channels,
                channels,
                kernel_size=3,
                padding=1,
                bias=False
            ),

            nn.BatchNorm2d(channels),

            nn.GELU(),

            nn.Conv2d(
                channels,
                channels,
                kernel_size=3,
                padding=1,
                bias=False
            ),

            nn.BatchNorm2d(channels),

            nn.GELU()

        )

    def forward(self,left,right):

        # -----------------------------------------
        # Resize to same width
        # -----------------------------------------

        if left.shape[-1] != right.shape[-1]:

            right = F.interpolate(

                right,

                size=left.shape[2:],

                mode="bilinear",

                align_corners=False

            )

        # -----------------------------------------
        # Absolute Difference
        # -----------------------------------------

        diff = torch.abs(left-right)

        # -----------------------------------------
        # Enhancement
        # -----------------------------------------

        diff = self.refine(diff)

        return diff


