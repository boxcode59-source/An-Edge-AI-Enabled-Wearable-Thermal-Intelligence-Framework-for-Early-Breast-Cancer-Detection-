import torch
import torch.nn as nn
import torch.nn.functional as F

class BTACFNet(nn.Module):

    def __init__(self):

        super().__init__()

        # Bilateral Decomposition
        self.decompose = BilateralFeatureDecomposition()

        # Left & Right Encoder
        self.encoder = ThermalPatternEncoder()

        # Difference Mapping
        self.diff = BilateralDifferenceMapping()

        # Adaptive Thermal Symmetry Learning
        self.atsl = ATSL()

        # Cross Attention
        self.cafm = CrossAttentionFusion()

        # Channel Spatial Attention
        self.cs_attention = ChannelSpatialAttention()

        # Final Fusion
        self.fusion = nn.Sequential(

            nn.Conv2d(
                1024,
                512,
                kernel_size=3,
                padding=1,
                bias=False
            ),

            nn.BatchNorm2d(512),

            nn.GELU(),

            nn.Conv2d(
                512,
                512,
                kernel_size=3,
                padding=1,
                bias=False
            ),

            nn.BatchNorm2d(512),

            nn.GELU()

        )

        self.pool = nn.AdaptiveAvgPool2d(1)

    def forward(self,x):

        # -------------------------------------
        # Bilateral Split
        # -------------------------------------

        left,right = self.decompose(x)

        # -------------------------------------
        # Thermal Encoder
        # -------------------------------------

        left = self.encoder(left)

        right = self.encoder(right)

        # -------------------------------------
        # Difference Map
        # -------------------------------------

        difference = self.diff(left,right)

        # -------------------------------------
        # Symmetry Learning
        # -------------------------------------

        symmetry = self.atsl(difference)

        # -------------------------------------
        # Cross Attention
        # -------------------------------------

        attention = self.cafm(left,right)

        # -------------------------------------
        # Channel Spatial Refinement
        # -------------------------------------

        attention = self.cs_attention(attention)

        # -------------------------------------
        # Resize
        # -------------------------------------

        symmetry = F.interpolate(

            symmetry,

            size=attention.shape[2:],

            mode="bilinear",

            align_corners=False

        )

        # -------------------------------------
        # Fusion
        # -------------------------------------

        fusion = torch.cat(

            [attention,symmetry],

            dim=1

        )

        fusion = self.fusion(fusion)

        embedding = self.pool(fusion)

        embedding = torch.flatten(embedding,1)

        return {

            "left_feature":left,

            "right_feature":right,

            "difference_feature":difference,

            "symmetry_feature":symmetry,

            "attention_feature":attention,

            "fusion_feature":fusion,

            "embedding":embedding

        }


